function createMap(target: string) {
  const map: Record<string, string> = {};
  const targetChars = Array.from(target);
  for (let i = 0; i < ALPHABET.length; i++) {
    map[ALPHABET[i]] = targetChars[i];
  }
  return map;
}

export const formatMaps = {
  bold: createMap(BOLD),
  boldSans: createMap(BOLD_SANS),
  italic: createMap(ITALIC),
  italicSans: createMap(ITALIC_SANS),
  boldItalic: createMap(BOLD_ITALIC),
  boldItalicSans: createMap(BOLD_ITALIC_SANS),
  sans: createMap(SANS),
  monospace: createMap(MONOSPACE),
  script: createMap(SCRIPT),
  doublestruck: createMap(DOUBLESTRUCK),
  fullwidth: createMap(FULLWIDTH),
};

const reverseMap: Record<string, string> = {};
[BOLD, BOLD_SANS, ITALIC, ITALIC_SANS, BOLD_ITALIC, BOLD_ITALIC_SANS, SANS, MONOSPACE, SCRIPT, DOUBLESTRUCK, FULLWIDTH].forEach(charset => {
  const chars = Array.from(charset);
  for (let i = 0; i < ALPHABET.length; i++) {
    reverseMap[chars[i]] = ALPHABET[i];
  }
});

export function unformatText(text: string): string {
  if (!text) return '';
  let result = '';
  for (const char of text) {
    if (char === '\u0332' || char === '\u0336') continue;
    result += reverseMap[char] || char;
  }
  return result;
}

export type FormatterStyle = keyof typeof formatMaps | 'underline' | 'strikethrough' | 'boldUnderline' | 'boldStrikethrough' | 'uppercase' | 'lowercase' | 'normal';

export function formatText(text: string, style: FormatterStyle): string {
  if (!text) return '';
  
  // First, unformat any existing styles to get clean ASCII
  const cleanText = unformatText(text);
  
  if (style === 'normal') return cleanText;
  if (style === 'uppercase') return cleanText.toUpperCase();
  if (style === 'lowercase') return cleanText.toLowerCase();

  // Normalize to NFD to separate base characters from diacritics (crucial for Vietnamese)
  const nfd = cleanText.normalize('NFD');
  let result = '';
  
  for (const char of nfd) {
    if (style === 'underline') {
      result += char + '\u0332';
    } else if (style === 'strikethrough') {
      result += char + '\u0336';
    } else if (style === 'boldUnderline') {
      result += (formatMaps.bold[char] || char) + '\u0332';
    } else if (style === 'boldStrikethrough') {
      result += (formatMaps.bold[char] || char) + '\u0336';
    } else {
      result += formatMaps[style as keyof typeof formatMaps][char] || char;
    }
  }
  
  // We do NOT normalize back to NFC because we want the combining marks 
  // to apply to the new mathematical alphanumeric symbols.
  return result;
}
